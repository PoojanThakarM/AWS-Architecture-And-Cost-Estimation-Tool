export interface CftContext {
  appName: string;
  environment: string;
  allServiceIds: Set<string>;
  /** Relational engine for RDS/Aurora (from plan.metadata.dbEngine). */
  dbEngine?: "postgres" | "mysql" | "none";
}

/* eslint-disable @typescript-eslint/no-explicit-any -- CloudFormation documents are free-form JSON */
type CfnObject = Record<string, any>;
/* eslint-enable @typescript-eslint/no-explicit-any */

export interface CftServiceSpec {
  serviceId: string;
  primaryType: string;
  relatedTypes?: string[];
  description: string;
  /** Needs the generated VPC (subnets / security groups). */
  requiresVpc?: boolean;
  generateResources: (ctx: CftContext) => CfnObject;
  generateOutputs?: (ctx: CftContext) => CfnObject;
}

const has = (ctx: CftContext, id: string) => ctx.allServiceIds.has(id);
const hasContainerCompute = (ctx: CftContext) => has(ctx, "ECS") || has(ctx, "Fargate");

/** Security group that application compute (ECS tasks / EC2) runs in. */
function computeSecurityGroupRef(ctx: CftContext): CfnObject | null {
  if (hasContainerCompute(ctx) || has(ctx, "EC2")) return { Ref: "AppComputeSecurityGroup" };
  return null;
}

/** Ingress rule letting the compute tier (only) reach a data-tier port. */
function dataTierIngress(ctx: CftContext, port: number, description: string): CfnObject[] {
  const src = computeSecurityGroupRef(ctx);
  if (!src) return [];
  return [{ IpProtocol: "tcp", FromPort: port, ToPort: port, SourceSecurityGroupId: src, Description: description }];
}

/** Generated (never hardcoded) master credentials for a database. */
function generatedDbSecret(logicalUser: string, description: string): CfnObject {
  return {
    Type: "AWS::SecretsManager::Secret",
    Properties: {
      Description: description,
      GenerateSecretString: {
        SecretStringTemplate: JSON.stringify({ username: logicalUser }),
        GenerateStringKey: "password",
        PasswordLength: 32,
        ExcludePunctuation: true,
        RequireEachIncludedType: true,
      },
    },
  };
}

const secretRef = (secret: string, key: "username" | "password") => ({
  "Fn::Sub": `{{resolve:secretsmanager:\${${secret}}:SecretString:${key}}}`,
});

/** Shared, generated database secret used by RDS / Aurora. */
function dbSecretResources(): CfnObject {
  return {
    DatabaseSecret: generatedDbSecret("dbadmin", "Generated master credentials for the application database"),
  };
}

