export interface CftGeneratorOptions {
  appName?: string;
  environment?: string;
  patternOverride?: string;
}

/**
 * Normalises a user-supplied application name into something every resource
 * name accepts (S3 buckets need lowercase; ALB/target-group names ≤ 32 chars
 * including the "-<env>-alb" suffix).
 */
export function sanitizeAppName(raw: string | undefined): string {
  const cleaned = (raw ?? "")
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 20)
    .replace(/-$/g, "");
  return cleaned || "aws-architect-app";
}

export function sanitizeEnvironment(raw: string | undefined): (typeof ALLOWED_ENVIRONMENTS)[number] {
  const e = (raw ?? "").trim().toLowerCase();
  return (ALLOWED_ENVIRONMENTS as readonly string[]).includes(e)
    ? (e as (typeof ALLOWED_ENVIRONMENTS)[number])
    : "dev";
}

/**
 * Synthesizes CloudFormation YAML string(s) from a ServicePlan or array of ServicePlans.
 * When passed an array of plans (1..N), returns an array of YAML strings.
 * When passed a single plan, returns a single YAML string.
 * Single-element arrays produce byte-identical output to single-path calls.
 */
export function generateCftYaml(plans: ServicePlan[], options?: CftGeneratorOptions): string[];
export function generateCftYaml(plan: ServicePlan, options?: CftGeneratorOptions): string;
export function generateCftYaml(
  planOrPlans: ServicePlan | ServicePlan[],
  options?: CftGeneratorOptions
): string | string[];
export function generateCftYaml(
  planOrPlans: ServicePlan | ServicePlan[],
  options?: CftGeneratorOptions
): string | string[] {
  if (Array.isArray(planOrPlans)) {
    return planOrPlans.map((p) => generateSingleCftYaml(p, options));
  }
  return generateSingleCftYaml(planOrPlans, options);
}

export function generateSingleCftYaml(plan: ServicePlan, options?: CftGeneratorOptions): string {
  const rawPattern = options?.patternOverride || plan.detectedPattern || "generic";
  const pattern = rawPattern.toLowerCase().trim();
  const serviceIds = Array.from(new Set(plan.awsMappings.map((m) => m.serviceId as string)));
  return buildTemplateYaml(
    serviceIds,
    pattern,
    sanitizeAppName(options?.appName),
    sanitizeEnvironment(options?.environment),
    plan.metadata?.dbEngine
  );
}

/**
 * Generates CFT YAML directly from an array of service IDs and pattern name.
 */
export function generateCftFromServices(
  pattern: string,
  serviceIds: string[],
  options?: CftGeneratorOptions
): string {
  return buildTemplateYaml(
    Array.from(new Set(serviceIds)),
    pattern.toLowerCase().trim(),
    sanitizeAppName(options?.appName),
    sanitizeEnvironment(options?.environment)
  );
}

/** Which plan services were rendered, added as prerequisites, or left out. */
export interface CftCoverage {
  rendered: string[];
  prerequisites: string[];
  unsupported: string[];
}

export function cftCoverage(serviceIds: string[]): CftCoverage {
  const unique = Array.from(new Set(serviceIds));
  const rendered = unique.filter((id) => CFT_SERVICE_RESOURCE_MAP[id]);
  const unsupported = unique.filter((id) => !CFT_SERVICE_RESOURCE_MAP[id]);
  const needsVpc = rendered.some((id) => CFT_SERVICE_RESOURCE_MAP[id].requiresVpc);
  const prerequisites = needsVpc && !rendered.includes("VPC") ? ["VPC"] : [];
  return { rendered, prerequisites, unsupported };
}

/**
 * Internal worker to construct and stringify the CloudFormation document.
 */
function buildTemplateYaml(
  serviceIds: string[],
  pattern: string,
  appName: string,
  environment: string,
  dbEngine?: "postgres" | "mysql" | "none"
): string {
  const coverage = cftCoverage(serviceIds);
  // Fargate and ECS render the same resources; keep one.
  const renderList = [...coverage.rendered, ...coverage.prerequisites].filter(
    (id, _, arr) => !(id === "Fargate" && arr.includes("ECS"))
  );
  const allServiceIds = new Set(renderList);
  const ctx: CftContext = { appName, environment, allServiceIds, dbEngine };

  const parameters: CfnObject = {
    Environment: {
      Type: "String",
      Default: environment,
      AllowedValues: [...ALLOWED_ENVIRONMENTS],
      Description: "Deployment target environment name",
    },
    AppName: {
      Type: "String",
      Default: appName,
      AllowedPattern: "^[a-z0-9][a-z0-9-]{0,19}$",
      ConstraintDescription: "lowercase letters, digits and hyphens, at most 20 characters",
      Description: "Application name used for resource naming and tagging",
    },
  };
  if (allServiceIds.has("Route53")) {
    parameters.DomainName = {
      Type: "String",
      Description: "Domain name for the Route 53 hosted zone (e.g. example.org)",
    };
  }
  if (allServiceIds.has("SageMaker")) {
    parameters.SageMakerImageUri = {
      Type: "String",
      Description: "ECR image URI of the inference container for your model",
    };
  }
  if (allServiceIds.has("CloudFront") && !allServiceIds.has("S3") && !allServiceIds.has("ALB")) {
    parameters.OriginDomainName = {
      Type: "String",
      Description: "Domain name of the origin server CloudFront should forward to",
    };
  }

  const doc: CfnObject = {
    AWSTemplateFormatVersion: "2010-09-09",
    Description: `AWS CloudFormation Template — Generated by AWS Architect for pattern "${pattern}". ${CFT_DISCLAIMER_TEXT}`,
    Metadata: {
      AwsArchitect: {
        Pattern: pattern,
        RenderedServices: coverage.rendered,
        PrerequisitesAdded: coverage.prerequisites.map((p) =>
          p === "VPC" ? "VPC (required by networked services in the plan)" : p
        ),
        // Services in the plan this generator cannot express yet. They are
        // part of the recommended architecture and must be provisioned separately.
        UnsupportedServices: coverage.unsupported,
        Notes: [
          "Generating or downloading this template does not create AWS resources.",
          "Private subnets have no NAT Gateway; add one if the data tier needs outbound internet access.",
          "The HTTP listener has no TLS certificate; add ACM + an HTTPS listener before production use.",
        ],
      },
    },
    Parameters: parameters,
    Resources: {},
    Outputs: {},
  };

  // Deterministic order: VPC first so readers see the network before its users.
  const ordered = [...renderList].sort((a, b) => (a === "VPC" ? -1 : b === "VPC" ? 1 : 0));
  for (const serviceId of ordered) {
    const spec = CFT_SERVICE_RESOURCE_MAP[serviceId];
    if (!spec) continue;
    Object.assign(doc.Resources, spec.generateResources(ctx));
    if (spec.generateOutputs) Object.assign(doc.Outputs, spec.generateOutputs(ctx));
  }

  // CloudFormation requires at least one resource. A wait-condition handle is
  // free and inert — it makes "nothing in this plan is supported yet" explicit
  // instead of inventing resources the plan never recommended.
  if (Object.keys(doc.Resources).length === 0) {
    doc.Resources.PlaceholderNoSupportedServices = {
      Type: "AWS::CloudFormation::WaitConditionHandle",
      Metadata: {
        Reason: "None of the plan's services has a CloudFormation mapping yet — see Metadata.AwsArchitect.UnsupportedServices.",
      },
    };
  }

  if (Object.keys(doc.Outputs).length === 0) {
    delete doc.Outputs;
  }

  const unsupportedComment =
    coverage.unsupported.length > 0
      ? `# NOT INCLUDED (no CloudFormation mapping yet): ${coverage.unsupported.join(", ")}\n` +
        "# These services are part of the recommended architecture; provision them separately.\n"
      : "";

  const yamlBody = stringify(doc, { indent: 2, lineWidth: 0 });
  return `${CFT_DISCLAIMER_COMMENT}${unsupportedComment}\n${yamlBody}`;
}

