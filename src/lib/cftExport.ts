export interface CftValidationResult {
  valid: boolean;
  errors: string[];
}

/**
 * Required properties for the resource types this generator emits. A subset
 * of the CloudFormation resource specification — enough to catch the
 * omissions that previously passed (ALB without subnets, EC2 without an AMI,
 * awsvpc ECS services without a network configuration, …). Full schema
 * checks are done offline with cfn-lint in the test guide.
 */
const REQUIRED_PROPERTIES: Record<string, string[][]> = {
  "AWS::ElasticLoadBalancingV2::LoadBalancer": [["Subnets", "SubnetMappings"]],
  "AWS::EC2::Instance": [["ImageId", "LaunchTemplate"]],
  "AWS::EC2::SecurityGroup": [["GroupDescription"]],
  "AWS::EC2::Subnet": [["VpcId"], ["CidrBlock", "Ipv4IpamPoolId"]],
  "AWS::ElasticLoadBalancingV2::TargetGroup": [["VpcId", "TargetType"]],
  "AWS::Lambda::Function": [["Code"], ["Role"]],
  "AWS::RDS::DBInstance": [["DBInstanceClass"]],
  "AWS::Redshift::Cluster": [["ClusterType"], ["NodeType"], ["DBName"], ["MasterUsername"]],
  "AWS::MSK::Cluster": [["BrokerNodeGroupInfo"], ["ClusterName"], ["KafkaVersion"], ["NumberOfBrokerNodes"]],
  "AWS::SageMaker::Model": [["ExecutionRoleArn"]],
  "AWS::ECS::TaskDefinition": [["ContainerDefinitions"]],
};

/* eslint-disable @typescript-eslint/no-explicit-any -- validator walks arbitrary parsed YAML */
/**
 * Validates a generated CloudFormation YAML template: YAML well-formedness,
 * format version, parameter schemas, resource types, logical IDs, Ref /
 * Fn::GetAtt / Fn::Sub / DependsOn integrity, required properties for known
 * types, and hardcoded credentials. Passing this is NOT an AWS-side validation.
 */
export function validateCloudFormationTemplate(yamlContent: string): CftValidationResult {
  const errors: string[] = [];

  let doc: any;
  try {
    doc = parse(yamlContent);
  } catch (err: unknown) {
    return { valid: false, errors: [`YAML parse error: ${err instanceof Error ? err.message : String(err)}`] };
  }

  if (!doc || typeof doc !== "object") {
    return { valid: false, errors: ["Template root is not a valid YAML object"] };
  }

  if (!doc.AWSTemplateFormatVersion) {
    errors.push("Missing required field: AWSTemplateFormatVersion");
  } else if (String(doc.AWSTemplateFormatVersion) !== "2010-09-09") {
    errors.push(`Invalid AWSTemplateFormatVersion: expected '2010-09-09', got '${doc.AWSTemplateFormatVersion}'`);
  }

  if (!doc.Description || typeof doc.Description !== "string") {
    errors.push("Missing or invalid Description");
  }

  const paramNames = new Set<string>();
  if (doc.Parameters) {
    if (typeof doc.Parameters !== "object") {
      errors.push("Parameters must be a map of parameter declarations");
    } else {
      for (const [pName, pVal] of Object.entries(doc.Parameters) as [string, any][]) {
        paramNames.add(pName);
        if (!pVal?.Type) {
          errors.push(`Parameter "${pName}" is missing required field: Type`);
        }
        if (Array.isArray(pVal?.AllowedValues) && pVal.Default !== undefined && !pVal.AllowedValues.includes(pVal.Default)) {
          errors.push(`Parameter "${pName}" Default "${pVal.Default}" is not one of its AllowedValues`);
        }
        if (typeof pVal?.AllowedPattern === "string" && pVal.Default !== undefined) {
          try {
            if (!new RegExp(pVal.AllowedPattern).test(String(pVal.Default))) {
              errors.push(`Parameter "${pName}" Default "${pVal.Default}" does not match its AllowedPattern`);
            }
          } catch {
            errors.push(`Parameter "${pName}" has an invalid AllowedPattern`);
          }
        }
      }
    }
  }

  const resourceNames = new Set<string>();
  if (!doc.Resources || typeof doc.Resources !== "object" || Object.keys(doc.Resources).length === 0) {
    errors.push("Missing or empty Resources section");
  } else {
    for (const [rId, rVal] of Object.entries(doc.Resources) as [string, any][]) {
      resourceNames.add(rId);

      if (!/^[a-zA-Z0-9]+$/.test(rId)) {
        errors.push(`Invalid logical ID "${rId}": must contain alphanumeric characters only`);
      }

      if (!rVal?.Type || typeof rVal.Type !== "string") {
        errors.push(`Resource "${rId}" is missing required field: Type`);
        continue;
      } else if (!/^AWS::[a-zA-Z0-9]+::[a-zA-Z0-9]+$/.test(rVal.Type)) {
        errors.push(`Resource "${rId}" has invalid AWS type pattern: "${rVal.Type}"`);
      }

      if (rVal.Properties && typeof rVal.Properties !== "object") {
        errors.push(`Resource "${rId}" Properties must be an object`);
        continue;
      }

      const props = rVal.Properties ?? {};
      for (const alternatives of REQUIRED_PROPERTIES[rVal.Type] ?? []) {
        if (!alternatives.some((p) => props[p] !== undefined)) {
          errors.push(`Resource "${rId}" (${rVal.Type}) is missing required property ${alternatives.join(" or ")}`);
        }
      }
      if (rVal.Type === "AWS::ECS::Service" && !props.NetworkConfiguration) {
        const td = doc.Resources[props.TaskDefinition?.Ref]?.Properties;
        if (td?.NetworkMode === "awsvpc") {
          errors.push(`Resource "${rId}" uses an awsvpc task definition but has no NetworkConfiguration`);
        }
      }
      for (const key of ["MasterUserPassword", "Password"]) {
        const v = props[key];
        if (typeof v === "string" && !v.startsWith("{{resolve:")) {
          errors.push(`Resource "${rId}" has a hardcoded ${key}; use a Secrets Manager dynamic reference`);
        }
      }
      const execRole = props.ExecutionRoleArn;
      if (typeof execRole === "string" && /:policy\//.test(execRole)) {
        errors.push(`Resource "${rId}" ExecutionRoleArn is a policy ARN, not a role ARN`);
      }
    }
  }

  const pseudoParams = new Set([
    "AWS::AccountId",
    "AWS::NotificationARNs",
    "AWS::NoValue",
    "AWS::Partition",
    "AWS::Region",
    "AWS::StackId",
    "AWS::StackName",
    "AWS::URLSuffix",
  ]);
  const known = (name: string) => paramNames.has(name) || resourceNames.has(name) || pseudoParams.has(name);

  function checkRefs(node: any, path: string): void {
    if (!node || typeof node !== "object") return;

    if (node.Ref !== undefined) {
      const refTarget = String(node.Ref);
      if (!known(refTarget)) {
        errors.push(`Dangling Ref at ${path}: "${refTarget}" is not a defined parameter, resource, or pseudo-parameter`);
      }
    }

    if (node["Fn::GetAtt"] !== undefined) {
      const target = node["Fn::GetAtt"];
      const targetResource = Array.isArray(target) ? target[0] : String(target).split(".")[0];
      if (!resourceNames.has(targetResource)) {
        errors.push(`Dangling Fn::GetAtt at ${path}: resource "${targetResource}" is not defined in Resources`);
      }
    }

    if (node["Fn::Sub"] !== undefined) {
      const sub = node["Fn::Sub"];
      const template = Array.isArray(sub) ? String(sub[0]) : String(sub);
      const localVars = Array.isArray(sub) && sub[1] && typeof sub[1] === "object" ? new Set(Object.keys(sub[1])) : new Set<string>();
      for (const m of template.matchAll(/\$\{([^}!]+)\}/g)) {
        const name = m[1].split(".")[0];
        if (!known(name) && !localVars.has(name)) {
          errors.push(`Dangling Fn::Sub variable at ${path}: "\${${m[1]}}" is not a parameter, resource, or pseudo-parameter`);
        }
      }
    }

    for (const [k, v] of Object.entries(node)) {
      checkRefs(v, `${path}.${k}`);
    }
  }

  if (doc.Resources && typeof doc.Resources === "object") {
    checkRefs(doc.Resources, "Resources");
    for (const [rId, rVal] of Object.entries(doc.Resources) as [string, any][]) {
      const deps = rVal?.DependsOn === undefined ? [] : Array.isArray(rVal.DependsOn) ? rVal.DependsOn : [rVal.DependsOn];
      for (const d of deps) {
        if (!resourceNames.has(String(d))) errors.push(`Resource "${rId}" DependsOn unknown resource "${d}"`);
      }
    }
  }
  if (doc.Outputs) {
    checkRefs(doc.Outputs, "Outputs");
  }

  return {
    valid: errors.length === 0,
    errors,
  };
}
