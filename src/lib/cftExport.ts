/**
 * cftExport.ts — CloudFormation Template (YAML) Generator
 *
 * Synthesizes AWS CloudFormation YAML templates from the single-path
 * ServicePlan contract. Generating or downloading a template never creates
 * AWS resources — deployment is a separate, explicit user action.
 *
 * Guarantees:
 * - Deterministic, closed mapping table: AWS service key → CloudFormation
 *   resource type + required properties.
 * - The template contains ONLY services from the plan, plus explicitly
 *   recorded prerequisites (a VPC for networked services). Services with no
 *   mapping are listed under Metadata.AwsArchitect.UnsupportedServices — never
 *   silently dropped and never replaced by unrelated "canonical" resources.
 * - No secrets in the template: database credentials are generated by
 *   Secrets Manager at deploy time and consumed via dynamic references.
 * - Least-privilege wiring: security groups only open the ports the plan's
 *   data flow needs; IAM policies are scoped to the template's own resources.
 * - Parameterized with Environment (dev/staging/prod) and AppName.
 * - Decision 33 Disclaimer: "Starting template, not production-ready IaC."
 *
 * Verified offline with cfn-lint (see docs/TESTING_GUIDE.md); that is a
 * schema/lint check, NOT an AWS-side validation or deployment.
 */

