/** Upper bound for diagram XML accepted by the extractor (DoS guard). */
export const MAX_DIAGRAM_XML_CHARS = 2_000_000;

/**
 * Extracts the detected pattern and list of AWS services from an mxGraph XML string.
 *
 * Diagrams generated by this app carry an explicit `serviceId="…"` attribute on
 * every service node, which is authoritative. Label matching is only a
 * fallback for older/hand-edited files — and it now matches whole display
 * names only, because substring matching on every cell (edge labels and
 * container titles included) produced phantom services.
 */
export function extractServicesFromDiagramXml(diagramXml: string): {
  pattern: string;
  serviceIds: string[];
} {
  const xml = diagramXml.slice(0, MAX_DIAGRAM_XML_CHARS);
  const serviceIds = new Set<string>();

  const patternMatch = xml.match(/pattern="([^"]+)"|<!-- Pattern: ([^ ]+) -->|detectedPattern="([^"]+)"/i);
  const pattern = (patternMatch?.[1] || patternMatch?.[2] || patternMatch?.[3] || "generic").toLowerCase();

  for (const m of xml.matchAll(/<mxCell\b[^>]*\bserviceId="([A-Za-z0-9]+)"/g)) {
    serviceIds.add(m[1]);
  }

  if (serviceIds.size === 0) {
    for (const match of xml.matchAll(/<mxCell\b(?=[^>]*\bvertex="1")[^>]+value="([^"]+)"/g)) {
      const rawValue = match[1]
        .replace(/&amp;/g, "&")
        .replace(/&lt;/g, "<")
        .replace(/&gt;/g, ">")
        .replace(/&#xa;|&#10;|\n/gi, " ")
        .toLowerCase()
        .trim();
      for (const [key, serviceId] of Object.entries(DISPLAY_NAME_TO_SERVICE_ID)) {
        if (rawValue.includes(key)) serviceIds.add(serviceId);
      }
    }
  }

  return { pattern, serviceIds: Array.from(serviceIds) };
}

/**
 * Generates CFT YAML directly from an existing draw.io diagram XML string.
 */
export function generateCftFromDiagramXml(diagramXml: string, fallbackPattern?: string): string {
  const extracted = extractServicesFromDiagramXml(diagramXml);
  const pattern = fallbackPattern || extracted.pattern;
  return generateCftFromServices(pattern, extracted.serviceIds);
}

